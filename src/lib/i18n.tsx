const DICTS: Record<Lang, Record<Key, string>> = { es, en, zh };
export const LANGS: Lang[] = ['zh', 'en', 'es'];
export const LANG_LABEL: Record<Lang, string> = { zh: '中', en: 'EN', es: 'ES' };
const FALLBACK_ORDER: Lang[] = ['en', 'es', 'zh'];

function detectLang(): Lang {
  const nav = (navigator.language || 'es').toLowerCase();
  if (nav.startsWith('zh')) return 'zh';
  if (nav.startsWith('en')) return 'en';
  return 'es';
}

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  /** Texto de la interfaz, con {variables} */
  t: (key: Key, vars?: Record<string, string | number>) => string;
  /** Nombre de algo de los datos en el idioma actual (o en otro si no está traducido) */
  n: (l: L | undefined) => string;
  /** Igual que n() pero dice en qué idioma ha salido */
  nl: (l: L | undefined) => { text: string; lang: Lang | null };
}

const Ctx = createContext<I18n | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useStored<Lang>('lang', getStored<Lang>('lang', detectLang()));
  useEffect(() => {
    document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : lang;
  }, [lang]);

  const nl = (l: L | undefined) => {
    if (!l) return { text: '?', lang: null };
    if (l[lang]) return { text: l[lang]!, lang };
    for (const code of FALLBACK_ORDER) if (l[code]) return { text: l[code]!, lang: code };
    return { text: '?', lang: null };
  };
  const value: I18n = {
    lang,
    setLang,
    t: (key, vars) => {
      let s = DICTS[lang][key] ?? es[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    n: l => nl(l).text,
    nl,
  };
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n fuera de LangProvider');
  return v;
}
